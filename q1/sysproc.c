int
sys_fork(void)
{
  return fork();
}

int
sys_exit(void)
{
  exit();
  return 0;  // not reached
}

int
sys_wait(void)
{
  return wait();
}

int
sys_kill(void)
{
  int pid;

  if(argint(0, &pid) < 0)
    return -1;
  return kill(pid);
}

int
sys_getpid(void)
{
  return myproc()->pid;
}

int
sys_sbrk(void)
{
  int addr;
  int n;

  if(argint(0, &n) < 0)
    return -1;
  addr = myproc()->sz;
  if(growproc(n) < 0)
    return -1;
  return addr;
}

int
sys_sleep(void)
{
  int n;
  uint ticks0;

  if(argint(0, &n) < 0)
    return -1;
  acquire(&tickslock);
  ticks0 = ticks;
  while(ticks - ticks0 < n){
    if(myproc()->killed){
      release(&tickslock);
      return -1;
    }
    sleep(&ticks, &tickslock);
  }
  release(&tickslock);
  return 0;
}

// return how many clock tick interrupts have occurred
// since start.
int
sys_uptime(void)
{
  uint xticks;

  acquire(&tickslock);
  xticks = ticks;
  release(&tickslock);
  return xticks;
}

int
sys_memstats(void)
{
  int total_pages = ntotal_pages();
  int free_pages = nfree_pages();
  int allocated = get_total_allocated();
  int freed = get_total_freed();
  int current = allocated - freed;
  cprintf("== Memory Statistics ==\n");
  cprintf("Total pages managed:    %d\n", total_pages);
  cprintf("Currently free:         %d\n", free_pages);
  cprintf("Total allocated (ever): %d\n", allocated);
  cprintf("Total freed (ever):     %d\n", freed);
  cprintf("Currently allocated:    %d (allocated - freed)\n", current);
  cprintf("=======================\n");
  return 0;
}
